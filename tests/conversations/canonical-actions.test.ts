import { afterEach, expect, it } from 'vitest';
import { Store } from '../../src/storage/store.js';
import { References } from '../../src/conversations/references.js';
import { CanonicalWrites } from '../../src/storage/conversation-writes.js';
import { LegacyArguments } from '../../src/slack/legacy-arguments.js';
import { migrateCanonicalConversations } from '../../src/slack/canonical-migration.js';
import { configFixture } from '../helpers/config.js';
const stores:Store[]=[];afterEach(()=>stores.splice(0).forEach(s=>s.close()));
it('accepts equivalent legacy retries using original bytes and rejects changed target/content',()=>{
  const s=new Store(':memory:');stores.push(s);s.register('research','test',[]);s.enqueue('research','start',{});const run=s.beginRun('research')!;
  s.prepareAction(run,'action',{workId:'work',operation:'messages.send',args:{target:{channel:'CTEST',thread:'1.000001'},text:'same'}});
  s.queueOutput('research','out',{target:{channel:'CTEST',thread:'1.000001'},text:'same'});s.transitionOutput('out','pending','sending');s.transitionOutput('out','sending','unknown',{reason:'timeout'});
  const action=s.action('action'),output=s.output('out');migrateCanonicalConversations(s,configFixture);
  const refs=new References(s),compat=new LegacyArguments(refs,configFixture),writes=new CanonicalWrites(s,refs,value=>compat.effect(value));
  const target=compat.args({target:{channel:'CTEST',thread:'1.000001'}}).target as {conversationId:string;threadId:string};
  expect(writes.prepareAction(run,'action',{workId:'work',operation:'messages.send',args:{target,text:'same'}})).toEqual(action);
  expect(writes.queueOutput('research','out',{target,text:'same'})).toEqual(output);
  expect(()=>writes.queueOutput('research','out',{target,text:'different'})).toThrow('identity conflict');
  expect(()=>writes.prepareAction(run,'action',{workId:'work',operation:'messages.send',args:{target:{conversationId:'CTEST'},text:'same'}})).toThrow('identity conflict');
  expect(s.action('action')).toEqual(action);expect(s.output('out')).toEqual(output);
  expect(()=>compat.args({target:{channel:'CTEST',conversationId:'CTEST'}})).toThrow();
});
it('persists explicit v2 requests and does not let callers choose envelope versions',()=>{
  const s=new Store(':memory:');stores.push(s);s.register('research','test',[]);migrateCanonicalConversations(s,configFixture);
  const refs=new References(s),writes=new CanonicalWrites(s,refs);refs.createConversation('channel','external','opaque-space');
  const row=writes.queueOutput('research','new',{target:{conversationId:'opaque-space'},text:'body'});
  expect(JSON.parse(row.request)).toEqual({format:'mate.effect.v2',target:{conversationId:'opaque-space'},text:'body'});
  expect(()=>writes.queueOutput('research','bad',{format:'mate.effect.v1',target:{conversationId:'opaque-space'},text:'body'})).toThrow('controlled by persistence');
  expect(s.output('bad')).toBeUndefined();
});
